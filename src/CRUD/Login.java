    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceptarActionPerformed
          
            String nom = txtNombre.getText();
            String pass = txtPassword.getText();
                     
            if(nom.trim().isEmpty() || pass.trim().isEmpty() ){
                JOptionPane.showMessageDialog(null,"Falta informacion ", "", JOptionPane.PLAIN_MESSAGE);
                
            }else if(Usuario.validarUsuario(nom, pass)){
                 JOptionPane.showMessageDialog(null,"Conectandose con SQLiteDB . . . ", "", JOptionPane.PLAIN_MESSAGE, icono);
                cn.setLG(this);
                cn.setVisible(true);
                this.setVisible(false);
                limpiar(txtNombre,txtPassword);
              
            }else{
                JOptionPane.showMessageDialog(null, "Nombre o contraseña incorrecto");
            }    
            
    }//GEN-LAST:event_btnAceptarActionPerformed

  
